void SSH1106_OLED_DrawPixel(word x, word y, byte color)
  {
  if ((x > SH1106_I2C_SSH1106_OLED_MAX_COLUMN) || (y > (SH1106_I2C_SSH1106_OLED_MAX_PAGE * 8 + 7))) return;
  if (!color) ssh1106_buffer[((y / 8) * 128) + x] &= ~(1 << (y % 8));
  else ssh1106_buffer[((y / 8) * 128) + x] |= (1 << (y % 8));
  }

void SSH1106_OLED_Line(word x_start, word y_start, word x_end, word y_end, byte color)
  {
  word x, y, addx, addy, dx, dy;
  signed long P;
  word i;
  dx = abs((word) (x_end - x_start));
  dy = abs((word) (y_end - y_start));
  x = x_start;
  y = y_start;

  if (x_start > x_end) addx = -1;
  else addx = 1;
  if (y_start > y_end) addy = -1;
  else addy = 1;
  if (dx >= dy)
    {
    P = 2 * dy - dx;

    for (i = 0; i <= dx; ++i)
      {
      SSH1106_OLED_DrawPixel(x, y, color);
      if (P < 0)
        {
        P += 2 * dy;
        x += addx;
        }
      else
        {
        P += 2 * dy - 2 * dx;
        x += addx;
        y += addy;
        }
      }
    }
  else
    {
    P = 2 * dx - dy;
    for (i = 0; i <= dy; ++i)
      {
      SSH1106_OLED_DrawPixel(x, y, color);

      if (P < 0)
        {
        P += 2 * dx;
        y += addy;
        }
      else
        {

        P += 2 * dx - 2 * dy;
        x += addx;
        y += addy;
        }
      }
    }
  }

