void SSH1106_OLED_Circle(word x0, word y0, word r, byte color)
  {
  word f = 1 - r;
  word ddF_x = 1;
  word ddF_y = -2 * r;
  word x = 0;
  word y = r;

  SSH1106_OLED_DrawPixel(x0, y0 + r, color);
  SSH1106_OLED_DrawPixel(x0, y0 - r, color);
  SSH1106_OLED_DrawPixel(x0 + r, y0, color);
  SSH1106_OLED_DrawPixel(x0 - r, y0, color);

  while (x < y)
    {
    if (f >= 0)
      {

      y--;
      ddF_y += 2;
      f += ddF_y;
      }
    x++;
    ddF_x += 2;
    f += ddF_x;

    SSH1106_OLED_DrawPixel(x0 + x, y0 + y, color);
    SSH1106_OLED_DrawPixel(x0 - x, y0 + y, color);
    SSH1106_OLED_DrawPixel(x0 + x, y0 - y, color);
    SSH1106_OLED_DrawPixel(x0 - x, y0 - y, color);
    SSH1106_OLED_DrawPixel(x0 + y, y0 + x, color);
    SSH1106_OLED_DrawPixel(x0 - y, y0 + x, color);
    SSH1106_OLED_DrawPixel(x0 + y, y0 - x, color);
    SSH1106_OLED_DrawPixel(x0 - y, y0 - x, color);
    }
  }

void SSH1106_OLED_Write(word x, word y, char value)
  {
  word font_idx = 0;
  word rowcnt = 0;
  word cnt = 0;
  byte b;
  word temp = 0;

  word cbyte, cx, cy;
  word cbit;

  if (cfont.y_size % 8 == 0)
    {
    font_idx = ((value - cfont.offset)*(cfont.x_size * (cfont.y_size / 8))) + 4;
    for (rowcnt = 0; rowcnt < (cfont.y_size / 8); rowcnt++)
      {
      for (cnt = 0; cnt < cfont.x_size; cnt++)
        {
        temp = *(cfont.font + font_idx + cnt + (rowcnt * cfont.x_size));
        for (b = 0; b < 8; b++)
          {
          if (temp & (1 << b))
            {
            if (cfont.inverted == 0) SSH1106_OLED_DrawPixel(x + cnt, y + (rowcnt * 8) + b, 1);
            else SSH1106_OLED_DrawPixel(x + cnt, y + (rowcnt * 8) + b, 0);
            }
          else
            {
            if (cfont.inverted == 0) SSH1106_OLED_DrawPixel(x + cnt, y + (rowcnt * 8) + b, 0);
            else SSH1106_OLED_DrawPixel(x + cnt, y + (rowcnt * 8) + b, 1);
            }
          }
        }
      }
    }
  else
    {
    font_idx = ((value - cfont.offset)*((cfont.x_size * cfont.y_size) / 8)) + 4;
    cbyte = *(cfont.font + font_idx);
    cbit = 7;
    for (cx = 0; cx < cfont.x_size; cx++)
      {
      for (cy = 0; cy < cfont.y_size; cy++)
        {
        if ((cbyte & (1 << cbit)) != 0)
          {
          if (cfont.inverted == 0) SSH1106_OLED_DrawPixel(x + cx, y + cy, 1);
          else SSH1106_OLED_DrawPixel(x + cx, y + cy, 0);
          }
        else
          {
          if (cfont.inverted == 0) SSH1106_OLED_DrawPixel(x + cx, y + cy, 0);
          else SSH1106_OLED_DrawPixel(x + cx, y + cy, 1);
          }
        cbit--;
        if (cbit < 0)
          {

          cbit = 7;
          font_idx++;
          cbyte = *(cfont.font + font_idx);
          }
        }
      }
    }
  }

void SSH1106_OLED_Write_Text(word x, word y, const char *text)
  {
  byte cnt;
  byte length;

  length = strlen((const char*) text);
  // if (x == RIGHT) x = 128 - (length * cfont.x_size);
  // if (x == CENTER) x = (128 - (length * cfont.x_size)) / 2;

  for (cnt = 0; cnt < length; cnt++) SSH1106_OLED_Write(x + (cnt * (cfont.x_size)), y, *text++);
  }

void SSH1106_OLED_Write_Dec(word x, word y, dword data)
  {
  char text[30];
  byte cnt;
  byte length;
  sprintf(text, "%d", data);
  length = strlen(text);
  // if (x == RIGHT) x = 128 - (length * cfont.x_size);
  // if (x == CENTER) x = (128 - (length * cfont.x_size)) / 2;
  for (cnt = 0; cnt < length; cnt++) SSH1106_OLED_Write(x + (cnt * (cfont.x_size)), y, text[cnt]);
  }

void SSH1106_OLED_INIT(void (*startFunc)(void), byte(*writeFunc)(byte), byte(*stopFunc)(void))
  {
  ssh1106_oled_i2c_start = startFunc;
  ssh1106_oled_i2c_write = writeFunc;
  ssh1106_oled_i2c_stop = stopFunc;
  ssh1106_oled_i2c_start();

  //SET I2C SLAVE WRITE ADDRESS
  ssh1106_oled_i2c_write(0x78);

  //SET TYPE TO COMMAND STREAM
  ssh1106_oled_i2c_write(SH1106_I2C_CONTROL_BYTE_CMD_STREAM);

  //DISPLAY OFF
  ssh1106_oled_i2c_write(SH1106_I2C_CMD_SET_DISPLAY_OFF);

  //SET COLUMN ADDRESS LOWER (2)
  //BECAUSE THIS CONTROLLER HAS RAM SIZE 132 X 64 WHEREAS OUR DISPLAY
  //IS 128 X 4. SO THE OLED IS MAPPED FROM RAM COLUMN 2 - COLUMN 130
  ssh1106_oled_i2c_write(SH1106_I2C_CMD_SET_COLUMN_LOWER_4 | 2);
  ssh1106_oled_i2c_write(SH1106_I2C_CMD_SET_COLUMN_UPPER_4 | 0);

  //SET START PAGE ADDRESS = 0
  ssh1106_oled_i2c_write(SH1106_I2C_CMD_SET_PAGE_ADDRESS | 0);

  //SET COMMON OUTPUT SCAN DIRECTION = TOP -> BOTTOM
  ssh1106_oled_i2c_write(SH1106_I2C_CMD_SET_COMMON_SCAN_DIRECTION | 8); //8 //0

  //ssh1106_oled_i2c_write(0x00);
  //ssh1106_oled_i2c_write(0x10);

  //SET DISPLAY START LINE = 0
  ssh1106_oled_i2c_write(SH1106_I2C_CMD_SET_DISPLAY_START_LINE | 0);

  //SET CONTRAST
  ssh1106_oled_i2c_write(SH1106_I2C_CMD_SET_CONTRAST_CONTROL_MODE);
  ssh1106_oled_i2c_write(0x7F);

  //SET SEGMENT REMAP
  ssh1106_oled_i2c_write(SH1106_I2C_CMD_SET_SEGMENT_REMAP | 1); //1 // 0

  //SET DISPLAY = NORMAL
  ssh1106_oled_i2c_write(SH1106_I2C_CMD_SET_DISPLAY_NORMAL);

  //SET MULTIPLEX RATIO = 63 (ALL ROWS)
  ssh1106_oled_i2c_write(SH1106_I2C_CMD_SET_MULTIPLEX_RATIO);
  ssh1106_oled_i2c_write(0x3F);

  //SET ENTIRE DISPLAY = ON
  ssh1106_oled_i2c_write(SH1106_I2C_CMD_SET_ENTIRE_DISPLAY_ON);

  //SET DISPLAY OFFSET = 0
  ssh1106_oled_i2c_write(SH1106_I2C_CMD_SET_DISPLAY_OFFSET_MODE);
  ssh1106_oled_i2c_write(0x00);

  //SET DISPLAY OSCILLATOR FREQUENCY
  ssh1106_oled_i2c_write(SH1106_I2C_CMD_SET_OSCILLATOR_FREQUENCY);
  ssh1106_oled_i2c_write(0xF0);

  //SET DISCHARGE-PRECHARGE PERIOD
  ssh1106_oled_i2c_write(SH1106_I2C_CMD_SET_DISCHARGE_PRECHARGE);
  ssh1106_oled_i2c_write(0x22);

  //SET COMMON PADS HARDWARE CONFIG
  ssh1106_oled_i2c_write(SH1106_I2C_CMD_COMMON_PADS_HARDWARE_CONFIG);
  ssh1106_oled_i2c_write(0x12);

  //SET COMMON PAD OUTPUT VOLTAGE
  ssh1106_oled_i2c_write(SH1106_I2C_CMD_COMMON_PADS_OUTPUT_VOLTAGE);
  ssh1106_oled_i2c_write(0x20);

  ssh1106_oled_i2c_write(0x8D);
  ssh1106_oled_i2c_write(0x14);

  //SET DISPLAY ON
  ssh1106_oled_i2c_write(SH1106_I2C_CMD_SET_DISPLAY_ON);


  ssh1106_oled_i2c_stop();

  SSH1106_OLED_SetFont(font_8x16BOLD);
  SSH1106_OLED_ClearDisplay();
  SSH1106_OLED_Update();
  }

void SSH1106_OLED_Update(void)
  {
  word counter = 0;
  word x = 0;
  word y = 0;

  for (y = 0; y < (SH1106_I2C_SSH1106_OLED_MAX_PAGE + 1); y++)
    {
    ssh1106_oled_i2c_start();
    ssh1106_oled_i2c_write(0x78);
    ssh1106_oled_i2c_write(SH1106_I2C_CONTROL_BYTE_CMD_STREAM);

    ssh1106_oled_i2c_write(SH1106_I2C_CMD_SET_COLUMN_UPPER_4);
    ssh1106_oled_i2c_write(SH1106_I2C_CMD_SET_COLUMN_LOWER_4 | 2);

    ssh1106_oled_i2c_write(SH1106_I2C_CMD_SET_PAGE_ADDRESS | y);
    ssh1106_oled_i2c_stop();

    ssh1106_oled_i2c_start();
    ssh1106_oled_i2c_write(0x78);
    ssh1106_oled_i2c_write(SH1106_I2C_CONTROL_BYTE_DATA_STREAM);

    for (x = 0; x < (SH1106_I2C_SSH1106_OLED_MAX_COLUMN + 1); x++)
      {
      ssh1106_oled_i2c_write(ssh1106_buffer[counter]);
      counter++;
      }
    ssh1106_oled_i2c_stop();
    }
  }

