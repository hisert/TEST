void SSH1306_OLED_Circle(word x0, word y0, word r, byte color)
  {
  word f = 1 - r;
  word ddF_x = 1;
  word ddF_y = -2 * r;
  word x = 0;
  word y = r;

  SSH1306_OLED_DrawPixel(x0, y0 + r, color);
  SSH1306_OLED_DrawPixel(x0, y0 - r, color);
  SSH1306_OLED_DrawPixel(x0 + r, y0, color);
  SSH1306_OLED_DrawPixel(x0 - r, y0, color);

  while (x < y)
    {
    if (f >= 0)
      {
      y--;
      ddF_y += 2;
      f += ddF_y;
      }
    x++;
    ddF_x += 2;
    f += ddF_x;

    SSH1306_OLED_DrawPixel(x0 + x, y0 + y, color);
    SSH1306_OLED_DrawPixel(x0 - x, y0 + y, color);
    SSH1306_OLED_DrawPixel(x0 + x, y0 - y, color);
    SSH1306_OLED_DrawPixel(x0 - x, y0 - y, color);
    SSH1306_OLED_DrawPixel(x0 + y, y0 + x, color);
    SSH1306_OLED_DrawPixel(x0 - y, y0 + x, color);
    SSH1306_OLED_DrawPixel(x0 + y, y0 - x, color);
    SSH1306_OLED_DrawPixel(x0 - y, y0 - x, color);
    }
  }

void SSH1306_OLED_Write(word x, word y, char value)
  {
  word font_idx = 0;
  word rowcnt = 0;
  word cnt = 0;
  byte b;
  word temp = 0;

  word cbyte, cx, cy;
  word cbit;

  if (cfont.y_size % 8 == 0)
    {
    font_idx = ((value - cfont.offset)*(cfont.x_size * (cfont.y_size / 8))) + 4;
    for (rowcnt = 0; rowcnt < (cfont.y_size / 8); rowcnt++)
      {
      for (cnt = 0; cnt < cfont.x_size; cnt++)
        {
        temp = *(cfont.font + font_idx + cnt + (rowcnt * cfont.x_size));
        for (b = 0; b < 8; b++)
          {
          if (temp & (1 << b))
            {
            if (cfont.inverted == 0) SSH1306_OLED_DrawPixel(x + cnt, y + (rowcnt * 8) + b, 1);
            else SSH1306_OLED_DrawPixel(x + cnt, y + (rowcnt * 8) + b, 0);
            }
          else
            {
            if (cfont.inverted == 0) SSH1306_OLED_DrawPixel(x + cnt, y + (rowcnt * 8) + b, 0);
            else SSH1306_OLED_DrawPixel(x + cnt, y + (rowcnt * 8) + b, 1);
            }
          }
        }
      }
    }
  else
    {
    font_idx = ((value - cfont.offset)*((cfont.x_size * cfont.y_size) / 8)) + 4;
    cbyte = *(cfont.font + font_idx);
    cbit = 7;
    for (cx = 0; cx < cfont.x_size; cx++)
      {
      for (cy = 0; cy < cfont.y_size; cy++)
        {
        if ((cbyte & (1 << cbit)) != 0)
          {
          if (cfont.inverted == 0) SSH1306_OLED_DrawPixel(x + cx, y + cy, 1);
          else SSH1306_OLED_DrawPixel(x + cx, y + cy, 0);
          }
        else
          {
          if (cfont.inverted == 0) SSH1306_OLED_DrawPixel(x + cx, y + cy, 0);
          else SSH1306_OLED_DrawPixel(x + cx, y + cy, 1);
          }
        cbit--;
        if (cbit < 0)
          {
          cbit = 7;
          font_idx++;
          cbyte = *(cfont.font + font_idx);
          }
        }
      }
    }
  }

void SSH1306_OLED_Write_Text(word x, word y, const char *text)
  {
  byte cnt;
  byte length;

  length = strlen((const char*) text);
  // if (x == RIGHT) x = 128 - (length * cfont.x_size);
  // if (x == CENTER) x = (128 - (length * cfont.x_size)) / 2;
  for (cnt = 0; cnt < length; cnt++) SSH1306_OLED_Write(x + (cnt * (cfont.x_size)), y, *text++);
  }

void SSH1306_OLED_Write_Text_Middle(word y, const char *text)
  {
  byte length = strlen(text);

  byte maxChars = 128 / cfont.x_size; // ekrana s??an karakter say?s?
  if (length > maxChars) length = maxChars;

  byte totalSpaces = maxChars - length;
  byte leftSpaces = totalSpaces / 2;

  word x = leftSpaces * cfont.x_size;

  for (byte cnt = 0; cnt < length; cnt++)
    {
    SSH1306_OLED_Write(x + (cnt * cfont.x_size), y, text[cnt]);
    }
  }

